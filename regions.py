NAME_COMPILED = [(n, f, re.compile(p, re.I)) for n, f, p in NAME_RULES]
CODE_COMPILED = [
    (n, f, re.compile(r"(?<![A-Za-z])" + code + r"(?:[-_ ]\d|[-_|]|$)", re.I))
    for n, f, code in CODE_RULES
]


def detect_region(name: str) -> tuple[str, str]:
    """返回 (地区名, 旗帜)，未识别返回 ("其他", "🌐")。"""
    for label, flag, pattern in NAME_COMPILED:
        if pattern.search(name or ""):
            return label, flag
    for label, flag, pattern in CODE_COMPILED:
        if pattern.search(name or ""):
            return label, flag
    return "其他", "🌐"


def strip_flags(name: str) -> str:
    """去掉名字里已有的国旗 emoji，并清理残留分隔符。"""
    return FLAG_RE.sub("", name or "").strip(" -_|·")
